import { expect, test } from '@playwright/test';
import fixture from '../../../docs/implementation/house-demo-fixture.json';

test('canvas-first workspace keeps its room across tool panels, house views and reload', async ({ page }, info) => {
  test.setTimeout(120_000);
  const failures: string[] = [];
  page.on('pageerror', (error) => failures.push(error.message));
  await page.route('**/api/v1/**', (route) => route.fulfill({ status: 401, contentType: 'application/json', body: JSON.stringify({ error: { code: 'UNAUTHORIZED', message: 'Guest' } }) }));
  await page.addInitScript((data) => {
    const scenes = data.scenes.map((scene, index) => index === 0 ? { ...scene, openings: [...scene.openings, { id: 'north-window', wall: 'N', kind: 'WINDOW', offset: -0.4, w: 1.2, h: 1.1, sill: 0.8 }] } : scene);
    if (!localStorage.getItem('mm_studio_v3')) localStorage.setItem('mm_studio_v3', JSON.stringify({ version: 3, state: { ...data, scenes, tutorialSeen: true, accountDraft: null, panelPos: null } }));
  }, fixture);
  await page.goto('/en/studio', { waitUntil: 'domcontentloaded' });
  const workspace = page.getByTestId('studio-workspace');
  await expect(workspace).toBeVisible({ timeout: 60_000 });
  const roomCanvas = page.locator('canvas').first();
  await expect(roomCanvas).toBeVisible({ timeout: 60_000 });
  const originalCanvas = await roomCanvas.elementHandle();
  await expect(roomCanvas.locator('xpath=ancestor::*[@data-wall-mode][1]')).toHaveAttribute('data-wall-mode', 'full');
  await page.getByRole('button', { name: 'Wall display', exact: true }).click();
  await expect(roomCanvas.locator('xpath=ancestor::*[@data-wall-mode][1]')).toHaveAttribute('data-wall-mode', 'cutaway');
  await page.getByRole('button', { name: 'Wall display', exact: true }).click();
  await expect(roomCanvas.locator('xpath=ancestor::*[@data-wall-mode][1]')).toHaveAttribute('data-wall-mode', 'full');
  const bounds = await roomCanvas.boundingBox();
  expect(bounds!.width).toBeGreaterThan(page.viewportSize()!.width * .9);
  expect(bounds!.height).toBeGreaterThan(page.viewportSize()!.height * .7);
  await page.getByRole('button', { name: 'Furniture', exact: true }).click();
  await expect(page.getByRole('complementary', { name: 'My pieces', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Minimize panel', exact: true }).press('Enter');
  await expect(page.getByRole('button', { name: 'Furniture', exact: true })).toHaveAttribute('aria-expanded', 'false');
  await page.getByRole('button', { name: 'Room', exact: true }).click();
  await expect(page.getByRole('complementary', { name: 'Room settings', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Floor: FAG', exact: true }).click();
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('mm_studio_v3')!).state.scenes[0].room.floorColor)).toBe('FAG');
  await page.getByRole('button', { name: 'Minimize panel', exact: true }).click();
  await page.getByRole('button', { name: 'Hide tools', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Furniture', exact: true })).toBeHidden();
  await expect(roomCanvas).toBeVisible();
  expect(await roomCanvas.boundingBox()).toEqual(bounds);
  await page.getByRole('button', { name: 'Show tools', exact: true }).press('Enter');
  expect(await originalCanvas!.evaluate((el) => el.isConnected)).toBe(true);
  await page.screenshot({ path: `../../docs/implementation/screenshots/studio-workspace-${info.project.name}.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  await page.getByRole('button', { name: 'House', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your house layout', exact: true })).toBeVisible();
  await expect(roomCanvas).toBeHidden();
  await expect(page.getByTestId('house-plan-opening')).toHaveCount(2);
  const windowSymbol = page.locator('[data-opening-id="north-window"]');
  await expect(windowSymbol).toHaveAttribute('transform', 'translate(-0.4 -2.045) rotate(0)');
  await expect(windowSymbol.locator('rect')).toHaveAttribute('width', '1.2');
  await page.getByRole('button', { name: 'Whole-house 3D', exact: true }).click();
  await expect(page.locator('canvas')).toHaveCount(2, { timeout: 30_000 });
  await expect(page.locator('canvas').nth(1)).toBeVisible();
  await expect(page.locator('canvas').nth(1).locator('xpath=ancestor::*[@data-wall-mode][1]')).toHaveAttribute('data-wall-mode', 'full');
  await page.screenshot({ path: `../../docs/implementation/screenshots/house-workspace-${info.project.name}.png`, fullPage: true });
  await page.getByRole('button', { name: 'Expand house tools', exact: true }).click();
  const width = page.getByLabel('Door width (m)', { exact: true });
  await width.fill('1.1'); await width.blur();
  const edited = await page.evaluate(() => JSON.parse(localStorage.getItem('mm_studio_v3')!).state);
  expect(edited.scenes[0].openings[0].w).toBe(1.1);
  expect(edited.scenes[1].openings[0].w).toBe(1.1);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await page.getByRole('button', { name: 'Minimize house tools', exact: true }).click();
  await page.getByRole('button', { name: 'House', exact: true }).click();
  await expect(roomCanvas).toBeVisible();
  expect(await originalCanvas!.evaluate((el) => el.isConnected)).toBe(true);
  expect(await roomCanvas.boundingBox()).toEqual(bounds);
  await page.reload({ waitUntil: 'domcontentloaded' });
  await expect(workspace).toBeVisible();
  await expect(roomCanvas).toBeVisible({ timeout: 60_000 });
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('mm_studio_v3')!).state);
  expect(saved.scenes).toHaveLength(2);
  expect(saved.house.connections).toHaveLength(1);
  expect(saved.scenes[0].room.floorColor).toBe('FAG');
  expect(failures).toEqual([]);
});
